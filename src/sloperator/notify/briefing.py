"""Daily briefing generation and principal notifications.

The briefing is assembled from computed facts (counts, action items with
provenance) so it is marked factual and needs no model call. Notifications
are persisted with an urgency level and delivered through the configured
mechanisms: a row per notification, an optional filesystem copy, and the
terminal rendering done by the CLI.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Any

from sloperator.artifacts.store import (
    ArtifactProvenance,
    ArtifactRecord,
    ArtifactStore,
    ArtifactType,
)
from sloperator.config.models import Config, Urgency
from sloperator.database.dao import to_db_time, utc_now
from sloperator.database.db import Database


@dataclass(frozen=True)
class BriefingResult:
    project_id: str
    date: str
    new_events: int
    active_threads: int
    open_action_items: int
    outstanding_requests: int
    series_updates: int
    artifact: ArtifactRecord
    notifications: int


class DailyBriefing:
    def __init__(self, db: Database, store: ArtifactStore, config: Config) -> None:
        self._db = db
        self._store = store
        self._config = config

    def generate(self, project_id: str, *, now: datetime | None = None) -> BriefingResult:
        moment = now or utc_now()
        since = moment - timedelta(days=1)
        conn = self._db.connect()

        new_events = int(
            conn.execute(
                "SELECT COUNT(*) AS n FROM events WHERE project_id = ? AND timestamp > ?",
                (project_id, to_db_time(since)),
            ).fetchone()["n"]
        )
        active_threads = int(
            conn.execute(
                "SELECT COUNT(*) AS n FROM threads WHERE project_id = ? AND last_activity_at > ?",
                (project_id, to_db_time(since)),
            ).fetchone()["n"]
        )
        items = conn.execute(
            """SELECT id, description, explicitness, confidence, source_event_ids_json
               FROM action_items
               WHERE project_id = ? AND status = 'open'
               ORDER BY CASE explicitness
                   WHEN 'EXPLICIT_REQUEST' THEN 0
                   WHEN 'EXPLICIT_COMMITMENT' THEN 1 ELSE 2 END, id""",
            (project_id,),
        ).fetchall()
        series_updates = int(
            conn.execute(
                """SELECT COUNT(*) AS n FROM patch_series
                   WHERE project_id = ? AND updated_at > ?""",
                (project_id, to_db_time(since)),
            ).fetchone()["n"]
        )
        outstanding = sum(1 for i in items if i["explicitness"] == "EXPLICIT_REQUEST")

        date = to_db_time(moment)[:10]
        content = self._render(project_id, date, new_events, active_threads, items, series_updates)
        artifact = self._store.save(
            project_id=project_id,
            artifact_type=ArtifactType.DAILY_BRIEFING,
            title=f"Daily briefing {date} — {project_id}",
            content=content,
            provenance=ArtifactProvenance(factual=True),
        )

        notifications = self._notify(project_id, date, artifact.id, new_events, outstanding)
        return BriefingResult(
            project_id=project_id,
            date=date,
            new_events=new_events,
            active_threads=active_threads,
            open_action_items=len(items),
            outstanding_requests=outstanding,
            series_updates=series_updates,
            artifact=artifact,
            notifications=notifications,
        )

    def _render(
        self,
        project_id: str,
        date: str,
        new_events: int,
        active_threads: int,
        items: list[Any],
        series_updates: int,
    ) -> str:
        lines = [
            f"# Daily briefing — {project_id} — {date}",
            "",
            "## Activity (last 24h)",
            f"- New events: {new_events}",
            f"- Threads with activity: {active_threads}",
            f"- Patch series updates: {series_updates}",
            "",
            f"## Open action items ({len(items)})",
        ]
        if not items:
            lines.append("- none")
        for row in items:
            lines.append(f"- [{row['explicitness']}] {row['description']} (item #{row['id']})")
        lines.append("")
        lines.append("_Generated by sloperator from persisted state; no model output._")
        return "\n".join(lines)

    def _notify(
        self,
        project_id: str,
        date: str,
        artifact_id: int,
        new_events: int,
        outstanding: int,
    ) -> int:
        if not self._config.notifications.enabled:
            return 0
        min_severity = self._config.notifications.min_urgency.severity
        planned: list[tuple[Urgency, str, str]] = [
            (Urgency.INFO, f"Briefing {date} ready", f"Daily briefing for {project_id} generated."),
        ]
        if outstanding:
            planned.append(
                (
                    Urgency.HIGH_PRIORITY,
                    f"{outstanding} outstanding request(s) in {project_id}",
                    "Explicit requests are awaiting a response; see open action items.",
                )
            )
        created = 0
        now = utc_now()
        for urgency, title, body in planned:
            if urgency.severity < min_severity:
                continue
            with self._db.transaction() as conn:
                cursor = conn.execute(
                    """INSERT INTO notifications (project_id, urgency, title, body,
                           artifact_id, created_at)
                       VALUES (?, ?, ?, ?, ?, ?)""",
                    (
                        project_id,
                        urgency.value,
                        title,
                        body,
                        artifact_id,
                        to_db_time(now),
                    ),
                )
                notification_id = int(cursor.lastrowid or 0)
                created += 1
            self._write_file_copy(notification_id, urgency, title, body)
        return created

    def _write_file_copy(
        self, notification_id: int, urgency: Urgency, title: str, body: str
    ) -> None:
        directory = self._config.notifications.directory
        if directory is None:
            return
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"notification-{notification_id}-{urgency.value.lower()}.md"
        path.write_text(f"# {title}\n\nUrgency: {urgency.value}\n\n{body}\n", encoding="utf-8")

    def list_notifications(
        self, *, min_urgency: Urgency | None = None, undelivered_only: bool = False
    ) -> list[dict[str, object]]:
        sql = "SELECT * FROM notifications"
        clauses: list[str] = []
        params: list[object] = []
        if min_urgency is not None:
            allowed = [u.value for u in Urgency if u.severity >= min_urgency.severity]
            clauses.append("urgency IN (" + ",".join("?" for _ in allowed) + ")")
            params.extend(allowed)
        if undelivered_only:
            clauses.append("delivered_at IS NULL")
        if clauses:
            sql += " WHERE " + " AND ".join(clauses)
        sql += " ORDER BY created_at DESC, id DESC"
        rows = self._db.connect().execute(sql, tuple(params)).fetchall()
        return [dict(row) for row in rows]
